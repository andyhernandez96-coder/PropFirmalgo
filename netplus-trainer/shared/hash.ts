/**
 * Question identity. Two questions are duplicates when their normalized text
 * matches, so the hash ignores case, punctuation and whitespace differences.
 * Pure JS so the browser preview and the server compute identical ids.
 */
export function normalizeQuestionText(text: string): string {
  return text
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/** cyrb53: fast 53-bit string hash. Collision risk is negligible for a personal bank. */
function cyrb53(str: string, seed = 0): number {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

export function questionHash(text: string): string {
  return 'q_' + cyrb53(normalizeQuestionText(text)).toString(16).padStart(14, '0');
}
